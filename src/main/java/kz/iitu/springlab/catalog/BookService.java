package kz.iitu.springlab.catalog;

import org.springframework.stereotype.Service;

import java.util.Comparator;
import java.util.List;
import java.util.Optional;

@Service
public class BookService {

    private final BookRepository repository;

    public BookService(BookRepository repository) {
        this.repository = repository;
    }

    /** All books when author is null, otherwise only those whose author contains the text. */
    public List<Book> findAll(String author) {
        return repository.findAll().stream()
                .filter(b -> author == null || author.isBlank()
                        || b.author().toLowerCase().contains(author.toLowerCase()))
                .sorted(Comparator.comparing(Book::id))
                .toList();
    }

    public Optional<Book> findById(long id) {
        return repository.findById(id);
    }

    public Book create(Book book) {
        // id is always generated by the repository for a new record
        return repository.save(new Book(null, book.title(), book.author(), book.year()));
    }

    public Optional<Book> replace(long id, Book book) {
        return repository.findById(id)
                .map(old -> repository.save(new Book(id, book.title(), book.author(), book.year())));
    }

    public boolean delete(long id) {
        return repository.deleteById(id);
    }

    /** Individual variant 1: case-insensitive search by a fragment of the title. */
    public List<Book> searchByTitle(String q) {
        String fragment = q == null ? "" : q.toLowerCase();
        return repository.findAll().stream()
                .filter(b -> b.title().toLowerCase().contains(fragment))
                .sorted(Comparator.comparing(Book::id))
                .toList();
    }
}
